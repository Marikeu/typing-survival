/** 일반 몬스터는 한글 기준 1~4글자의 정보 교과 용어만 사용합니다. */
export const SHORT_WORDS=Array.from(new Set(WORDS.filter(word=>{
  const len=Array.from(word).length;
  return len>=1&&len<=4&&/^[가-힣]+$/.test(word);
})));

export function pickGameWord():string {
  return SHORT_WORDS[Math.floor(Math.random()*SHORT_WORDS.length)] || '정보';
}

/** 보스는 원문을 띄어쓰기 단위로만 나눕니다. 긴 어절도 그대로 입력합니다. */
export function splitBossPhrase(phrase:string):string[]{
  return phrase.trim().split(/\s+/).filter(Boolean);
}
